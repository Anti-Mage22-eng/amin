"""Цветовая тема приложения.

Всё оформление собрано здесь: чтобы поменять палитру (например, вернуть светлую
тему), достаточно поправить значения в этом файле — остальной код их только читает.
Тёмно-бордовая палитра задана hex-кодами: у Flet нет готовых «бордовых» цветов.
"""

from __future__ import annotations

import re

import flet as ft

# --- фон и поверхности ----------------------------------------------------
BG = "#3A0A15"            # фон приложения — тёмно-бордовый
PANEL = "#4B0F1F"         # фон карточек-панелей
PANEL_DEEP = "#2A0710"    # самые тёмные блоки (плашки, активная кнопка)
SURFACE = "#FFFFFF"       # «бумага» для таблиц, диаграмм и карточек машин

# --- текст -----------------------------------------------------------------
ON_RED = "#FFFFFF"        # основной текст на тёмном фоне
ON_RED_DIM = "#E9C6D0"    # подписи и пояснения на тёмном фоне
ON_SURFACE = "#2A0710"    # текст на белой «бумаге»
MUTED_ON_SURFACE = "#8A6B74"

# --- цифры -----------------------------------------------------------------
NUMBER_ON_RED = "#FFFFFF"        # крупные цифры на тёмном фоне
NUMBER_ON_SURFACE = "#B00030"    # цифры на белой «бумаге» — яркий малиновый
ACCENT = "#FFC107"               # акцент: активная кнопка, «шапки» цифр
ACCENT_SOFT = "#FFE9A8"          # мягкий акцент для фона под цифрой цены

BORDER = ft.Border.all(1, "#7A2740")

# у OutlinedButton нет параметра color — цвет задаётся через стиль
OUTLINE_BUTTON_STYLE = ft.ButtonStyle(
    color=ON_RED,
    icon_color=ON_RED,
    side=ft.BorderSide(1, "#B06078"),
)

# --- размеры ---------------------------------------------------------------
KPI_NUMBER_SIZE = 40       # крупные цифры в KPI-карточках
BIG_NUMBER_SIZE = 32       # цифра цены и итоговой оценки в карточке автомобиля
CARD_NUMBER_SIZE = 24      # пробег, год и другие числа в карточке
TABLE_NUMBER_SIZE = 20     # цифры в таблицах
SCORE_NUMBER_SIZE = 28     # оценки отдельных агентов

LABEL_SIZE = 13            # подписи у цифр
SMALL_LABEL_SIZE = 11      # совсем мелкие пояснения
BODY_SIZE = 15             # обычный текст в карточках
CHART_HEIGHT = 250

# ячейка «похожа на число»: 91, «1 350 000 ₽», «95 000 км», «2019 – 2024»
_NUMBER_CELL = re.compile(r"^[0-9][0-9\s.,/–—%₽км]*$")


def looks_numeric(text: str) -> bool:
    """Нужно ли выделять значение как число (жирным и контрастным цветом)."""
    return bool(_NUMBER_CELL.match(str(text).strip()))
